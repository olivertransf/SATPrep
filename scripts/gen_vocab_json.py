def build_words():
    seen = set()
    out = []
    for w, d in WORDS_RAW:
        lw = w.lower()
        if lw in COMMON_BLOCKLIST:
            continue
        if lw in seen:
            continue
        seen.add(lw)
        pos = classify_pos(w)
        out.append((w, d, pos))
    for w, d, pos in REPLACEMENTS:
        lw = w.lower()
        if lw in seen:
            continue
        seen.add(lw)
        out.append((w, d, pos))
    return out


def main():
    words = build_words()
    words_payload = [
        {"id": str(i + 1), "word": w, "definition": d, "partOfSpeech": p}
        for i, (w, d, p) in enumerate(words)
    ]
    roots_payload = [
        {"id": str(i + 1), "root": r, "meaning": m, "origin": o, "examples": e}
        for i, (r, m, o, e) in enumerate(ROOTS)
    ]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "Studium", "Resources", "sat-vocab-flashcards.json")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"words": words_payload, "roots": roots_payload}, f, ensure_ascii=False, indent=2)
    counts = {}
    for _, _, p in words:
        counts[p] = counts.get(p, 0) + 1
    print(len(words), "words (POS counts:", counts, "),", len(ROOTS), "roots ->", path)


if __name__ == "__main__":
    main()
