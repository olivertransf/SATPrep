def classify_pos(word: str) -> str:
    w = word.lower()
    if w in POS_MANUAL:
        return POS_MANUAL[w]
    if w.endswith("ly") and len(w) > 4 and w not in ADV_EXCEPT:
        return "adverb"
    for suf in NOUN_SUFFIX:
        if w.endswith(suf):
            return "noun"
    if w.endswith("ous") or w.endswith("ive") or (w.endswith("ent") and not w.endswith("ment")) or w.endswith("ant"):
        if w.endswith("ment"):
            pass
        else:
            return "adj"
    for suf in ("able", "ible", "ary", "ory", "ful", "less", "ial", "ic"):
        if w.endswith(suf):
            return "adj"
    if w.endswith("ish") or w.endswith("ive"):
        return "adj"
    if w.endswith("ize") or w.endswith("ise") or w.endswith("ify"):
        return "verb"
    if w.endswith("en") and len(w) > 4 and w not in {"often", "given", "women", "children"}:
        return "verb"
    if w.endswith("ate") and len(w) > 5:
        return "verb"
    if re.search(r"(ify|ize|ise)$", w):
        return "verb"
    # gerund-style nouns
    if w.endswith("ing") and len(w) > 5:
        return "other"
    return "other"


